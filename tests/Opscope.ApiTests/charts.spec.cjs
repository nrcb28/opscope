'use strict';
const assert = require('node:assert/strict');
const { normalize, SeriesBuffer, decimate } = require('../../src/Opscope.Api/Web/realtime-charts.js');
const start = Date.parse('2026-10-25T12:00:00Z');
const metric = (i, overrides = {}) => ({ schemaVersion: 1, source: 'local-lightweight', sequence: i + 1, sampledAtUtc: new Date(start + i * 5000).toISOString(), elapsedMilliseconds: i * 5000, sampleIntervalSeconds: 5, cpuPercent: 30, memoryPercent: 60, ...overrides });
assert.equal(normalize(metric(0)).cpu, 30);
assert.equal(normalize(metric(0, { cpuPercent: null })).cpu, null);
assert.equal(normalize(metric(0, { cpuPercent: 0 })).cpu, 0);
assert.equal(normalize(metric(0, { cpuPercent: NaN })), null);
assert.equal(normalize(metric(0, { cpuPercent: 101 })), null);
assert.equal(normalize(metric(0, { schemaVersion: 2 })), null);
assert.equal(normalize(metric(0, { sequence: -1 })), null);
assert.equal(normalize(metric(0, { elapsedMilliseconds: -1 })), null);
assert.equal(normalize({ collectedAtUtc: 'invalid', cpuUsedPercent: 5 }), null);
const buffer = new SeriesBuffer();
for (let i = 0; i < 800; i++) assert.equal(buffer.push(normalize(metric(i))), true);
assert.equal(buffer.points.length, 720);
assert.equal(buffer.points[0].sequence, 81);
assert.equal(buffer.push(normalize(metric(799))), false);
assert.equal(buffer.push(normalize(metric(798))), false);
assert.equal(buffer.push(normalize(metric(800, { elapsedMilliseconds: 5 }))), false);
assert.equal(buffer.push(normalize(metric(800, { sampledAtUtc: '2026-10-24T12:00:00Z', clockAdjusted: true }))), true);
assert.equal(buffer.points.at(-1).clockAdjusted, true);
assert.equal(buffer.push(normalize(metric(803))), true);
assert.equal(buffer.dropped, 2);
const points = Array.from({ length: 720 }, (_, i) => ({ time: start + i * 5000, cpu: i === 357 ? 100 : i === 495 ? 0 : 30 }));
const reduced = decimate(points, 'cpu', 80);
assert.ok(reduced.length < points.length);
assert.ok(reduced.some(p => p.cpu === 100));
assert.ok(reduced.some(p => p.cpu === 0));
assert.ok(reduced.every((point, index) => !index || point.time > reduced[index - 1].time));
points[222].cpu = null;
assert.ok(decimate(points, 'cpu', 80).some(p => p.cpu === null));
const snapshot = normalize({ collectedAtUtc: '2026-10-25T12:00:00Z', cpuUsedPercent: 17, memoryUsedPercent: 44, hostname: 'private-host' });
assert.equal(snapshot.memory, 44);
assert.equal(Object.hasOwn(snapshot, 'hostname'), false);
console.log('PASS: chart normalization, bounded buffering, monotonic ordering and peak-preserving decimation.');
